const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const db = require('../dinosaurs.json');
const before = require('../docs/backups/anatomy-02/manifest.json');
const after = require('../docs/anatomy-02.json');
const id = 'bothriolepis-canadensis';
const sha = p => crypto.createHash('sha256').update(fs.readFileSync(path.join(root,p))).digest('hex');
assert.equal(db.dinosaurs.length,112);
assert.equal(sha('dinosaurs.json'),before.databaseSha256,'All species data, credits and narration must remain unchanged');
assert.deepEqual(Object.keys(after).filter(k=>k!=='databaseSha256'),[id]);
assert.equal(sha('docs/backups/anatomy-02/images/'+id+'.webp'),before.allActiveImageSha256[id]);
assert.notEqual(after[id].sha256,before.allActiveImageSha256[id]);
assert.equal(after[id].width,1536);
assert.equal(after[id].height,1024);
for (const a of db.dinosaurs) assert.equal(sha(a.image.src),a.id===id?after[id].sha256:before.allActiveImageSha256[a.id],a.id);
console.log('PASS: approved Bothriolepis, exact backup, 111 other images and complete database preserved.');

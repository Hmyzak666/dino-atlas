const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const { historicalDatabase: db, readHistoricalFile } = require('./helpers/approved-nine.cjs');
const before = require('../docs/backups/anatomy-03/manifest.json');
const after = require('../docs/anatomy-03.json');
const next = {...require('../docs/anatomy-04.json'), ...require('../docs/approved-nine-2026-11-05.json').images, ...require('../docs/approved-three-2026-11-06.json').images, ...require('../docs/approved-twelve-2026-11-06.json').images, ...require('../docs/approved-thirty-2026-11-08.json').images};
const id = 'qilinyu-rostrata';
const sha = p => crypto.createHash('sha256').update(readHistoricalFile(path.join(root,p))).digest('hex');
assert.equal(db.dinosaurs.length,112);
assert.equal(sha('dinosaurs.json'),before.databaseSha256,'All species data, credits and narration must remain unchanged');
assert.deepEqual(Object.keys(after).filter(k=>k!=='databaseSha256'),[id]);
assert.equal(sha('docs/backups/anatomy-03/images/'+id+'.webp'),before.allActiveImageSha256[id]);
assert.notEqual(after[id].sha256,before.allActiveImageSha256[id]);
assert.equal(after[id].width,1536);
assert.equal(after[id].height,1024);
for (const a of db.dinosaurs) assert.equal(sha(a.image.src),next[a.id]?.sha256 || (a.id===id?after[id].sha256:before.allActiveImageSha256[a.id]),a.id);
console.log('PASS: approved Qilinyu, exact backup, 111 other images and complete database preserved.');

const assert = require('node:assert/strict');
const app = require('../app.js');
const db = require('../dinosaurs.json');
const state = {category:'all', query:'', period:'all', diet:'all', favoritesOnly:false, favorites:new Set()};
const find = options => app.filteredDinosaurs(db.dinosaurs, {...state, ...options});
assert.equal(app.normalize('ČESKÝ ještěr'), 'cesky jester');
assert.equal(find({query:'  BRACHIOSAURUS  '})[0].id, 'brachiosaurus-altithorax');
assert.deepEqual(find({query:'neexistujici-zvire'}), []);
assert.equal(find({category:'dinosaur', period:'triassic'}).length, 7);
assert.equal(find({category:'pterosaur', period:'triassic'}).length, 2);
assert.equal(find({category:'marine-reptile', period:'triassic'}).length, 2);
assert.deepEqual(find({category:'pterosaur', diet:'herbivore'}), []);
assert.deepEqual(find({category:'marine-reptile', query:'eoraptor'}), []);
assert.deepEqual(find({favoritesOnly:true}), []);
const favorites = new Set(['brachiosaurus-altithorax','tyrannosaurus-rex','missing-id']);
assert.deepEqual(find({favoritesOnly:true, favorites, period:'jurassic'}).map(a=>a.id), ['brachiosaurus-altithorax']);
const tyrannosaurus = db.dinosaurs.find(a=>a.id==='tyrannosaurus-rex');
for (const alias of tyrannosaurus.aliases) assert.ok(find({query:alias}).some(a=>a.id===tyrannosaurus.id), alias);
assert.equal(find({query:'eudimorphodon ranzii'})[0].id,'eudimorphodon-ranzii');
console.log('PASS: Czech normalization, case/spacing, scientific names/aliases, empty results, period/category/diet intersections, and stale favorite IDs.');
